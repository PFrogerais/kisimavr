"""Generate the SPICE model of a servomotor or of an HC-SR04 ultrasonic sensor.

Usage (KiCad project):
  python3 tools/make_module_lib.py servo -o ~/kicad/my_project/servo.lib
  python3 tools/make_module_lib.py hcsr04 --dist 30 --rate -50 -o hcsr04.lib

Both are d_cosim instances of mcu_cosim.so: the timing is exact and each
event is printed in the terminal.

servo  ("device" "servo"), sub-circuit SERVO, pins SIG VCC GND ANGLE:
  the width of each SIG pulse sets the angle (--min us -> 0 deg, --max us
  -> 180 deg, Arduino Servo defaults 544 / 2400 us); the horn turns at
  --speed deg/s (600: SG90). ANGLE is a voltage output, 1 V = 1 degree, to
  plot the position. SIG threshold 1.4 V (3.3 V and 5 V signals).
hcsr04 ("device" "hcsr04"), sub-circuit HCSR04, pins VCC TRIG ECHO GND
  (the order of the module header): a TRIG pulse of 10 us or more starts a
  measurement; ECHO goes high (VCC level) for 58.3 us per cm of --dist (cm),
  which can move at --rate cm/s. With a 3.3 V microcontroller, ECHO (5 V)
  needs a divider, as on the real module.
"""

import argparse
import os
import sys


def wrap(items, indent="+ ", width=76):
    lines, line = [], ""
    for it in items:
        if line and len(line) + 1 + len(it) > width - len(indent):
            lines.append(line)
            line = it
        else:
            line = f"{line} {it}" if line else it
    lines.append(line)
    return f"\n{indent}".join(lines)


def parse_args():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("kind", choices=["servo", "hcsr04"])
    ap.add_argument("-o", "--output", help="output .lib (default: stdout)")
    ap.add_argument("--so", default=os.path.join(here, "..", "build", "mcu_cosim.so"),
                    help="mcu_cosim.so (default: ../build/mcu_cosim.so)")
    ap.add_argument("--name", default="", help="suffix: SERVO_<NAME>, for several modules")
    ap.add_argument("--irreversible", type=int,
                    help="d_cosim rank, distinct for each co-simulated part "
                         "(default: servo 13, hcsr04 14)")
    ap.add_argument("--min", type=float, default=544.0, help="servo: pulse for 0 deg (us)")
    ap.add_argument("--max", type=float, default=2400.0, help="servo: pulse for 180 deg (us)")
    ap.add_argument("--speed", type=float, default=600.0, help="servo: speed (deg/s)")
    ap.add_argument("--start", type=float, default=90.0, help="servo: angle at t = 0 (deg)")
    ap.add_argument("--dist", type=float, default=20.0, help="hcsr04: distance (cm)")
    ap.add_argument("--rate", type=float, default=0.0, help="hcsr04: distance change (cm/s)")
    ap.add_argument("--log", action="store_true", help="hcsr04: print every measurement")
    ap.add_argument("--relative", action="store_true", help=argparse.SUPPRESS)
    args = ap.parse_args()
    if args.irreversible is None:
        args.irreversible = 13 if args.kind == "servo" else 14
    if not args.relative:
        args.so = os.path.abspath(os.path.expanduser(args.so))
        if not os.path.isfile(args.so):
            print(f"warning: plug-in not found: {args.so}", file=sys.stderr)
        if args.so != args.so.lower():
            print("warning: the .so path contains upper case letters; KiCad lower-cases\n"
                  "         it and ngspice will not find it (use e.g. a link in /opt).",
                  file=sys.stderr)
    return args


def servo(a, sub, tag, w):
    sim_args = ['"device"', '"servo"', '"min"', f'"{a.min:g}"', '"max"', f'"{a.max:g}"',
                '"speed"', f'"{a.speed:g}"', '"start"', f'"{a.start:g}"', '"name"', f'"{sub}"']
    w("* =============================================================================")
    w(f"* {sub} : RC servomotor (kisimavr), {a.min:g}..{a.max:g} us -> 0..180 deg, "
      f"{a.speed:g} deg/s")
    w("*   Pulse widths measured in mcu_cosim.so (d_cosim, \"device\" \"servo\"):")
    w(f"*   {sub}> 90 deg (pulse 1472 us) is printed for each position reached.")
    w("*")
    w("* Pins: SIG VCC GND ANGLE   (ANGLE: voltage output, 1 V = 1 degree)")
    w(f"*   KiCad: Sim.Device = SUBCKT, Sim.Name = {sub}")
    w(f"* d_cosim rank {a.irreversible} (--irreversible): distinct from the other parts.")
    w("* Generated by tools/make_module_lib.py")
    w("* =============================================================================")
    w("")
    w(f'.model {tag}_core d_cosim simulation="{a.so}"')
    w("+ sim_args=[" + wrap(sim_args) + "]")
    w(f"+ irreversible={a.irreversible}")
    w(f".model {tag}_in adc_bridge(in_low=1.2 in_high=1.6)")
    w(f".model {tag}_bit dac_bridge(out_low=0 out_high=1 out_undef=0 t_rise=1u t_fall=1u)")
    w("")
    w(f".subckt {sub} SIG VCC GND ANGLE")
    w(f"aIn [SIG] [d_sig] {tag}_in")
    bits = " ".join(f"b{k}" for k in range(8))
    w(f"aServo [d_sig] [{bits}] null {tag}_core")
    w(f"aBits [{bits}] [" + " ".join(f"a{k}" for k in range(8)) + f"] {tag}_bit")
    w("* Angle in degrees (1 V = 1 deg)")
    w("Bangle ANGLE GND V = " + " + ".join(f"{1 << k}*V(a{k})" for k in range(8)))
    w("* Signal input (about 10 kohm), supply current at rest (about 10 mA at 5 V)")
    w("Rsig SIG GND 10k")
    w("Rsupply VCC GND 500")
    w(f".ends {sub}")


def hcsr04(a, sub, tag, w):
    sim_args = ['"device"', '"hcsr04"', '"dist"', f'"{a.dist:g}"', '"rate"', f'"{a.rate:g}"',
                '"name"', f'"{sub}"'] + (['"log"', '"1"'] if a.log else [])
    w("* =============================================================================")
    w(f"* {sub} : HC-SR04 ultrasonic distance sensor (kisimavr), obstacle at {a.dist:g} cm"
      + (f", {a.rate:g} cm/s" if a.rate else ""))
    w("*   Timing in mcu_cosim.so (d_cosim, \"device\" \"hcsr04\"): TRIG >= 10 us, ECHO")
    w("*   high 250 us after TRIG falls, for 58.3 us per cm (38 ms: out of range).")
    w("*")
    w("* Pins: VCC TRIG ECHO GND (header of the module); ECHO at the VCC level")
    w(f"*   KiCad: Sim.Device = SUBCKT, Sim.Name = {sub}, e.g. on a 4-pin connector:")
    w("*   Sim.Pins = 1=VCC 2=TRIG 3=ECHO 4=GND")
    w(f"* d_cosim rank {a.irreversible} (--irreversible): distinct from the other parts.")
    w("* Generated by tools/make_module_lib.py")
    w("* =============================================================================")
    w("")
    w(f'.model {tag}_core d_cosim simulation="{a.so}"')
    w("+ sim_args=[" + wrap(sim_args) + "]")
    w(f"+ irreversible={a.irreversible}")
    w(f".model {tag}_in adc_bridge(in_low=0.8 in_high=2.0)")
    w(f".model {tag}_bit dac_bridge(out_low=0 out_high=1 out_undef=0 t_rise=50n t_fall=50n)")
    w("")
    w(f".subckt {sub} VCC TRIG ECHO GND")
    w(f"aIn [TRIG] [d_trig] {tag}_in")
    w(f"aSensor [d_trig] [d_echo] null {tag}_core")
    w(f"aEcho [d_echo] [echo_l] {tag}_bit")
    w("* ECHO output: 0 / VCC through 100 ohm")
    w("Becho GND ECHO I = (V(echo_l) * V(VCC,GND) - V(ECHO,GND)) / 100")
    w("* TRIG input (10 kohm pull-down), supply current (about 15 mA at 5 V)")
    w("Rtrig TRIG GND 10k")
    w("Rsupply VCC GND 330")
    w(f".ends {sub}")


def main():
    a = parse_args()
    base = "SERVO" if a.kind == "servo" else "HCSR04"
    suffix = "".join(ch for ch in a.name if ch.isalnum() or ch == "_").upper()
    sub = f"{base}_{suffix}" if suffix else base
    tag = sub.lower()
    out = []
    (servo if a.kind == "servo" else hcsr04)(a, sub, tag, out.append)
    text = "\n".join(out) + "\n"
    if a.output:
        with open(a.output, "w") as f:
            f.write(text)
        print(f"written {a.output}", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
