"""Generate the SPICE model of a character LCD (HD44780, 16x2 by default).

Usage (KiCad project):
  python3 tools/make_lcd_lib.py -o ~/kicad/my_project/lcd.lib

The display is a second d_cosim instance of mcu_cosim.so ("device" "hd44780"):
it reads RS, R/W, E and D0..D7 from the circuit and prints each screen
(terminal, and lcd_log.txt next to the .lib). Sub-circuit pins, in the order
of the 16-pin module and of the KiCad symbol Display_Character:WC1602A:
  1 VSS  2 VDD  3 VO  4 RS  5 R/W  6 E  7..14 D0..D7  15 LED+  16 LED-

Electrical side: inputs with CMOS thresholds (1.5 / 3.5 V), internal
pull-ups on RS, R/W and D0..D7 (about 100 uA, as on the HD44780), 1.5 mA
supply current, backlight LED (about 3 V), VO not modelled (1 Mohm).
"""

import argparse
import os
import sys

INPUTS = ["RS", "RW", "E"] + [f"D{i}" for i in range(8)]
PINS = ["VSS", "VDD", "VO", "RS", "RW", "E"] + [f"D{i}" for i in range(8)] + ["LEDP", "LEDN"]


def wrap(items, indent="+ ", width=76):
    lines, line = [], ""
    for it in items:
        if line and len(line) + 1 + len(it) > width - len(indent):
            lines.append(line)
            line = it
        else:
            line = f"{line} {it}" if line else it
    lines.append(line)
    return f"\n{indent}".join(lines)


def parse_args():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", help="output .lib (default: stdout)")
    ap.add_argument("--so", default=os.path.join(here, "..", "build", "mcu_cosim.so"),
                    help="mcu_cosim.so (default: ../build/mcu_cosim.so)")
    ap.add_argument("--cols", type=int, default=16, help="characters per row (default 16)")
    ap.add_argument("--rows", type=int, default=2, help="rows (default 2)")
    ap.add_argument("--log", help="screens file (default: lcd_log.txt next to the .lib, '' = none)")
    ap.add_argument("--name", default="LCD", help="label of the messages (default LCD)")
    ap.add_argument("--irreversible", type=int, default=10,
                    help="d_cosim rank, distinct from every MCU of the netlist (default 10)")
    ap.add_argument("--relative", action="store_true", help=argparse.SUPPRESS)
    args = ap.parse_args()
    if not (8 <= args.cols <= 40 and 1 <= args.rows <= 4):
        ap.error("cols must be 8..40 and rows 1..4")

    if args.relative:    # Repository copy used by the ngspice/ tests.
        args.log = "../lcd_log.txt" if args.log is None else args.log
        return args
    base = os.path.dirname(os.path.abspath(args.output)) if args.output else os.getcwd()
    args.so = os.path.abspath(os.path.expanduser(args.so))
    if args.log is None:
        args.log = os.path.join(base, "lcd_log.txt")
    elif args.log:
        args.log = os.path.abspath(os.path.expanduser(args.log))
    if not os.path.isfile(args.so):
        print(f"warning: plug-in not found: {args.so}", file=sys.stderr)
    if args.so != args.so.lower():
        print("warning: the .so path contains upper case letters; KiCad lower-cases\n"
              "         it and ngspice will not find it (use e.g. a link in /opt).",
              file=sys.stderr)
    return args


def main():
    a = parse_args()
    sub = f"LCD{a.cols:02d}{a.rows:02d}"
    tag = sub.lower()
    sim_args = (['"device"', '"hd44780"', '"cols"', f'"{a.cols}"', '"rows"', f'"{a.rows}"',
                 '"name"', f'"{a.name}"'] + (['"lcdlog"', f'"{a.log}"'] if a.log else []))
    pins = " ".join(f"{n}={p}" for n, p in enumerate(PINS, 1))

    out = []
    w = out.append
    w("* =============================================================================")
    w(f"* {sub} : character LCD {a.cols}x{a.rows}, HD44780 controller (kisimavr)")
    w("*   The controller runs in mcu_cosim.so (d_cosim, \"device\" \"hd44780\"): each")
    w("*   screen is printed in the terminal and in the lcdlog file.")
    w("*")
    w("* Pins: 1 VSS  2 VDD  3 VO  4 RS  5 R/W  6 E  7..14 D0..D7  15 LED+  16 LED-")
    w("*   4-bit wiring (LiquidCrystal): D4..D7 only, D0..D3 left open.")
    w("*   R/W: tie to GND (read cycles are not modelled).")
    w("*")
    w("* KiCad: works with the official symbol Display_Character:WC1602A;")
    w(f"*   Sim.Device = SUBCKT, Sim.Name = {sub}, Sim.Pins =")
    w(f"*   {pins}")
    w("*")
    w(f"* Several co-simulated parts: each needs its own d_cosim rank (here {a.irreversible},")
    w("*   option --irreversible; the MCU keeps 1).")
    w("* Generated by tools/make_lcd_lib.py")
    w("* =============================================================================")
    w("")
    w(f'.model {tag}_core d_cosim simulation="{a.so}"')
    w("+ sim_args=[" + wrap(sim_args) + "]")
    w(f"+ irreversible={a.irreversible}")
    w(f".model {tag}_in adc_bridge(in_low=1.5 in_high=3.5)")
    w(f".model {tag}_bl D(IS=1e-20 N=2.6 RS=5)")
    w("")
    w(f".subckt {sub} " + " ".join(PINS))
    w("* Inputs read by the controller (falling edge of E)")
    w("aIn [" + " ".join(INPUTS) + "]")
    w("+ [" + " ".join(f"d_{p.lower()}" for p in INPUTS) + f"] {tag}_in")
    w("aLcd [" + " ".join(f"d_{p.lower()}" for p in INPUTS) + f"] null null {tag}_core")
    w("* Internal pull-ups (about 100 uA at 5 V) on RS, R/W, D0..D7")
    for p in INPUTS:
        if p != "E":
            w(f"Rpu{p.lower()} {p} VDD 50k")
    w("* E: high impedance input")
    w("Re E VSS 10meg")
    w("* Supply current of the module (about 1.5 mA at 5 V)")
    w("Rsupply VDD VSS 3.3k")
    w("* Contrast input (not modelled)")
    w("Rvo VO VSS 1meg")
    w("* Backlight LED")
    w(f"Dbl LEDP LEDN {tag}_bl")
    w(f".ends {sub}")
    text = "\n".join(out) + "\n"
    if a.output:
        with open(a.output, "w") as f:
            f.write(text)
        print(f"written {a.output}", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
