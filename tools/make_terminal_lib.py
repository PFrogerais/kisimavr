"""Write a SPICE model of a serial terminal (USB-serial converter).

The sub-circuit USB_SERIE stands for the ATmega16U2 of the Arduino UNO and
the PC terminal behind it: its TXD pin sends timed text lines as real UART
frames (PWL source), its RXD pin is a high-impedance input, its DTR pin is
held high (no reset). The frames go through the circuit to the RXD pin of
the co-simulated ATmega328P, which decodes them.

  python3 tools/make_terminal_lib.py terminal.txt -o terminal.lib [--baud 115200]

Script format (same as the "uartin" file of the plug-in), one line per send:
  <time> <text>        e.g.  2m Bonjour\\n
  time: SPICE suffixes f p n u m, optional trailing s; '#' starts a comment.
  escapes: \\n \\r \\t \\\\ \\s (space) \\xHH
A line that starts before the previous one is sent waits for it.
"""

import argparse
import os
import re
import sys

SCALE = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "": 1.0}


def parse_time(text):
    m = re.fullmatch(r"([0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?)([fpnum]?)s?", text)
    if not m:
        raise ValueError(f"invalid time '{text}'")
    return float(m.group(1)) * SCALE[m.group(2)]


def unescape(text):
    out = bytearray()
    i = 0
    while i < len(text):
        c = text[i]
        if c != "\\":
            out += c.encode("latin-1")
            i += 1
            continue
        if i + 1 >= len(text):
            raise ValueError("trailing '\\'")
        e = text[i + 1]
        simple = {"n": b"\n", "r": b"\r", "t": b"\t", "\\": b"\\", "s": b" "}
        if e in simple:
            out += simple[e]
            i += 2
        elif e == "x":
            digits = text[i + 2:i + 4]
            if not re.fullmatch(r"[0-9a-fA-F]{2}", digits):
                raise ValueError("\\x needs two hexadecimal digits")
            out.append(int(digits, 16))
            i += 4
        else:
            raise ValueError(f"unknown escape '\\{e}'")
    return bytes(out)


def parse_script(content):
    events = []
    for number, raw in enumerate(content.splitlines(), 1):
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        parts = line.strip().split(None, 1)
        try:
            when = parse_time(parts[0])
            if len(parts) < 2:
                raise ValueError("no text after the time")
            events.append((when, unescape(parts[1])))
        except ValueError as err:
            raise SystemExit(f"line {number}: {err}")
    events.sort(key=lambda e: e[0])    # Stable: same time keeps file order.
    return events


def pwl_points(events, baud, high, rise):
    """(time, volts) corners of the TXD waveform, idle high, 8N1, LSB first."""
    bit = 1.0 / baud
    points = [(0.0, high)]
    level = high
    free = 0.0                          # End of the last stop bit.

    def set_level(t, v):
        nonlocal level
        if v != level:
            points.append((t, level))
            points.append((t + rise, v))
            level = v

    for when, data in events:
        t = max(when, free)
        for byte in data:
            bits = [0] + [(byte >> k) & 1 for k in range(8)] + [1]
            for k, b in enumerate(bits):
                set_level(t + k * bit, high if b else 0.0)
            t += 10 * bit
        free = t
    return points


def fmt(value):
    return f"{value:.9g}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("script", help="timed text lines (see the format above)")
    ap.add_argument("-o", "--output", help="output .lib (default: stdout)")
    ap.add_argument("--baud", type=float, default=115200, help="bit rate (default 115200)")
    ap.add_argument("--vhigh", type=float, default=5.0, help="high level in volts (default 5)")
    ap.add_argument("--rise", default="100n", help="edge time (default 100n)")
    args = ap.parse_args()

    with open(args.script, encoding="utf-8") as f:
        events = parse_script(f.read())
    points = pwl_points(events, args.baud, args.vhigh, parse_time(args.rise))

    body = [f"{fmt(t)} {fmt(v)}" for t, v in points]
    lines = [f"* Serial terminal (USB-serial converter), generated by tools/make_terminal_lib.py",
             f"* from {os.path.basename(args.script)}: {args.baud:g} bauds 8N1, "
             f"{len(events)} line(s). Do not edit: regenerate.",
             "* Pins: TXD (output, to the RXD of the MCU), RXD (input), DTR (held high), GND",
             ".subckt USB_SERIE TXD RXD DTR GND",
             "VTX TXD GND PWL("]
    for i in range(0, len(body), 6):
        lines.append("+ " + " ".join(body[i:i + 6]))
    lines += ["+ )",
              "RRX RXD GND 1meg",
              f"VDTR DTR GND DC {fmt(args.vhigh)}",
              ".ends USB_SERIE", ""]
    text = "\n".join(lines)
    if args.output:
        with open(args.output, "w") as f:
            f.write(text)
        print(f"written {args.output}", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
